"""Pydantic v2 domain schemas for Onboarding, Document Extraction, and KYC Screening."""

import enum
import uuid
from datetime import date, datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


def utc_now() -> datetime:
    return datetime.now(timezone.utc)


class ApplicantType(str, enum.Enum):
    INDIVIDUAL = "INDIVIDUAL"
    BUSINESS = "BUSINESS"


class DocumentType(str, enum.Enum):
    PASSPORT = "PASSPORT"
    DRIVERS_LICENSE = "DRIVERS_LICENSE"
    NATIONAL_ID = "NATIONAL_ID"
    UTILITY_BILL = "UTILITY_BILL"
    COMPANY_REGISTRATION = "COMPANY_REGISTRATION"


class RiskRating(str, enum.Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class ApplicationStatus(str, enum.Enum):
    SUBMITTED = "SUBMITTED"
    PROCESSING = "PROCESSING"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    PENDING_HUMAN_REVIEW = "PENDING_HUMAN_REVIEW"


class DocumentPayload(BaseModel):
    """Submitted raw document record."""
    model_config = ConfigDict(frozen=True)

    document_id: str = Field(default_factory=lambda: f"doc_{uuid.uuid4().hex[:10]}")
    doc_type: DocumentType
    document_number: str
    issuing_country: str = "US"
    raw_content: str  # OCR text or simulated document payload
    expiry_date: Optional[str] = None  # YYYY-MM-DD
    holder_name: Optional[str] = None
    holder_dob: Optional[str] = None


class ExtractedDocumentData(BaseModel):
    """Normalized structured data extracted from a document by the extraction agent."""
    document_id: str
    doc_type: DocumentType
    full_name: str
    id_number: str
    dob: Optional[str] = None
    expiry_date: Optional[str] = None
    address: Optional[str] = None
    registration_number: Optional[str] = None
    beneficial_owners: List[str] = Field(default_factory=list)
    is_expired: bool = False
    defect_detected: bool = False
    defect_reason: Optional[str] = None
    confidence: float = 0.95


class ScreeningMatch(BaseModel):
    """Sanctions or PEP watchlist match result."""
    matched_name: str
    searched_query: str
    list_type: str  # OFAC_SDN, EU_SANCTIONS, PEP
    match_score: float  # 0.0 to 1.0
    country: Optional[str] = None
    program: Optional[str] = None
    is_exact_match: bool = False


class OnboardingApplicationRequest(BaseModel):
    """Customer application payload submitted via API or Portal."""
    model_config = ConfigDict(frozen=True)

    applicant_type: ApplicantType = ApplicantType.INDIVIDUAL
    legal_name: str
    email: str
    declared_dob: Optional[str] = None
    declared_address: str
    country: str = "US"
    documents: List[DocumentPayload] = Field(default_factory=list)
    business_registration_number: Optional[str] = None
    declared_beneficial_owners: List[str] = Field(default_factory=list)


class OnboardingDisposition(BaseModel):
    """Final decision and recommendation generated by the Onboarding Squad."""
    application_id: str
    legal_name: str
    applicant_type: ApplicantType
    risk_rating: RiskRating
    recommended_action: str  # APPROVE, REJECT, ESCALATE_TO_ANALYST
    confidence: float
    evidence: List[str] = Field(default_factory=list)
    defects_found: List[str] = Field(default_factory=list)
    screening_hits: List[ScreeningMatch] = Field(default_factory=list)
    approval_ticket_id: Optional[str] = None
    status: ApplicationStatus
    rationale: str
    evaluated_at: datetime = Field(default_factory=utc_now)
